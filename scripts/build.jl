function k_theory_csv(data)
    io = IOBuffer()
    println(io, "id,ring,field,p,f,e,n,r,exponents,order_exponent,status,new")
    for D in data, g in D.groups
        R = D.ring
        K = R.field
        fields = (
            R.id,
            ring_ascii(R),
            K.ascii,
            K.p,
            K.f,
            K.e,
            R.n,
            g.r,
            join(g.exponents, ";"),
            sum(g.exponents; init=0),
            g.status,
            isnew(g),
        )
        println(io, join(fields, ","))
    end
    return String(take!(io))
end

