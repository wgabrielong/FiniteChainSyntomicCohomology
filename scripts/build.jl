const SOURCE = "B. Antieau, A. Krause, T. Nikolaus, On the K-theory of Z/p^n, arXiv:2405.04329"

jstr(x) = JSON3.write(x)
jlist(v) = "[" * join(v, ",") * "]"

function k_theory_json(data, akn)
    io = IOBuffer()
    println(io, "{")
    println(io, "  \"format\": ", jstr(FORMAT), ",")
    println(io, "  \"akn\": ", jstr(SOURCE), ",")
    println(io, "  \"conventions\": ", jstr(CONVENTIONS), ",")
    println(io, "  \"rings\": [")
    for (k, D) in enumerate(data)
        R = D.ring
        K = R.field
        family = R.family == :akn ? "akn_appendix_A" : "quadratic_Q2"
        println(io, "    {")
        println(
            io,
            "      \"id\": $(jstr(R.id)), \"ring\": $(jstr(ring_ascii(R))), ",
            "\"family\": $(jstr(family)),",
        )
        println(
            io,
            "      \"field\": $(jstr(K.ascii)), \"lmfdb_label\": $(jstr(K.lmfdb)), ",
            "\"defining_polynomial\": $(jstr(K.poly)),",
        )
        println(
            io,
            "      \"p\": $(K.p), \"f\": $(K.f), \"e\": $(K.e), \"n\": $(R.n), ",
            "\"htilde\": $(jlist(K.htilde)), \"E\": [$(join(jlist.(K.E), ","))],",
        )
        if R.family == :akn
            a = akn[(K.p, R.n)]
            println(
                io,
                "      \"akn\": {\"section\": $(jstr(a.section)), \"page\": $(a.page), ",
                "\"label\": $(jstr(a.label)), \"max_degree\": $(a.max_degree)},",
            )
        else
            println(io, "      \"akn\": null,")
        end
        comp = (; (k => v for (k, v) in pairs(D.run) if k ∉ (:ring, :id))...)
        println(io, "      \"computation\": ", JSON3.write(comp), ",")
        println(io, "      \"groups\": [")
        rows = map(D.groups) do g
            return "        {\"r\": $(g.r), \"exponents\": $(jlist(g.exponents)), " *
                   "\"status\": \"$(g.status)\", \"new\": $(isnew(g))}"
        end
        println(io, join(rows, ",\n"))
        println(io, "      ]")
        println(io, k == length(data) ? "    }" : "    },")
    end
    println(io, "  ]")
    println(io, "}")
    return String(take!(io))
end

# --- data/k_theory.csv ------------------------------------------------------------------------

function k_theory_csv(data)
    io = IOBuffer()
    println(io, "id,ring,field,p,f,e,n,r,exponents,order_exponent,status,new")
    for D in data, g in D.groups
        R = D.ring
        K = R.field
        fields = (
            R.id,
            ring_ascii(R),
            K.ascii,
            K.p,
            K.f,
            K.e,
            R.n,
            g.r,
            join(g.exponents, ";"),
            sum(g.exponents; init=0),
            g.status,
            isnew(g),
        )
        println(io, join(fields, ","))
    end
    return String(take!(io))
end

# --- tables/<id>.md ---------------------------------------------------------------------------

function degrees_phrase(rs)
    isempty(rs) && return ""
    runs = UnitRange{Int}[]
    for r in sort(rs)
        if !isempty(runs) && last(runs[end]) == r - 1
            runs[end] = first(runs[end]):r
        else
            push!(runs, r:r)
        end
    end
    name(u) = length(u) == 1 ? kr(first(u)) : "$(kr(first(u)))–$(kr(last(u)))"
    return join(name.(runs), ", ")
end

zp(p) = "Z$(sub(p))"
lmfdb_link(K::Field) = "[$(K.lmfdb)](https://www.lmfdb.org/padicField/$(K.lmfdb))"
field_name(K::Field) = isempty(K.alias) ? K.name : "$(K.name) = $(K.alias)"
# "x^2 + 2x + 2" as "x² + 2x + 2", and in the variable z
poly_pretty(s) = replace(s, r"\^(\d+)" => m -> sup(m[2:end]))
poly_md(s) = replace(poly_pretty(s), "x" => "z")

function akn_status_paragraph(io, D, a)
    nprinted = count_status(D, "printed")
    nx = count_status(D, "x")
    nnew = count(isnew, D.groups)
    xs = [g.r for g in D.groups if g.status == "x"]
    head = "The table of [AKN, §$(a.section), p. $(a.page)] covers K_1–K_$(a.max_degree) for this ring"
    if nx == 0
        println(
            io,
            "$head. Its $nprinted groups agree with the ones below. ",
            "**$nnew groups are new here**: $(kr(a.max_degree + 1))–$(kr(RMAX)).",
        )
    else
        println(
            io,
            "$head. It prints $nprinted groups, which agree with the ones below, and marks $nx ",
            "degrees x (not computed within 48 hours: $(degrees_phrase(xs))). ",
            "**$nnew groups are new here**: the $nx marked x and ",
            "$(kr(a.max_degree + 1))–$(kr(RMAX)).",
        )
    end
    println(io)
    return println(
        io,
        "New groups are in **bold**. The last column gives the status in [AKN]: *printed*, ",
        "*x* (marked x, not computed within 48 hours) or *beyond* (after the last row of the ",
        "table).",
    )
end

function quadratic_ring_paragraph(io, R::Ring, classes, twins_of)
    K = R.field
    n = R.n
    if K.e == 1
        println(
            io,
            "K = $(field_name(K)) is the unramified quadratic extension of Q₂ (LMFDB ",
            "$(lmfdb_link(K))), so ϖ = 2 and R = O_K/2$(sup(n)) = W$(sub(n))(F₄), where ",
            "W(F₄) = Z₂[x]/(x² + x + 1). |R| = 4$(sup(n)).",
        )
    else
        println(
            io,
            "K = $(field_name(K)) is ramified over Q₂, with e = 2 and discriminant exponent ",
            "$(K.c) (LMFDB $(lmfdb_link(K))). R = O_K/ϖ$(sup(n)) = Z₂[z]/(E(z), z$(sup(n))) ",
            "with E(z) = $(poly_md(K.poly)), the defining polynomial of the LMFDB, and ϖ a root ",
            "of E. |R| = 2$(sup(n)).",
        )
    end
    if is_truncated_polynomial(R)
        println(io)
        println(
            io,
            "Since n ≤ e, R = F₂[z]/z². Hesselholt and Madsen computed the K-groups of these ",
            "rings (cited in [AKN, §1.1, p. 2]): K_{2i−1}(F_q[z]/zⁿ; Z_p) ≅ ",
            "W_{ni}(F_q)/V_n W_i(F_q) and K_{2i−2}(F_q[z]/zⁿ; Z_p) = 0 for i ≥ 2. Every group ",
            "below agrees with their formula, so none is new.",
        )
    end
    k = findfirst(c -> R.id in c, classes)
    others = k === nothing ? String[] : filter(!=(R.id), classes[k])
    if !isempty(others)
        println(io)
        names = join(["[$(ring_by_id(o).field.name)]($o.md)" for o in others], ", ")
        println(
            io,
            "O_K/ϖ$(sup(n)) is the same ring for K = $names (see the ",
            "[coincidences](../README.md#coincidences)), so those tables equal this one.",
        )
    end
    tw = get(twins_of, R.id, String[])
    if !isempty(tw)
        println(io)
        names = join(["[$(ring_by_id(o).field.name)]($o.md)" for o in tw], ", ")
        println(
            io,
            "O_K/ϖ$(sup(n)) for K = $names is a different ring, but it has the same K-groups ",
            "K_1–K_$RMAX (see the [coincidences](../README.md#coincidences)).",
        )
    end
    println(io)
    if is_truncated_polynomial(R)
        println(io, "The last column gives the status: *Hesselholt–Madsen*.")
    else
        println(
            io,
            "[AKN] tabulate no ring of this kind, so all $RMAX groups are new relative to ",
            "their tables. They are in **bold**.",
        )
    end
end

function ring_page(D, akn, classes, twins_of)
    R = D.ring
    K = R.field
    p = K.p
    run = D.run
    io = IOBuffer()
    println(io, "# p-adic K-theory of $(ring_title(R))")
    println(io)
    println(
        io,
        "[All rings](../README.md) · the same data: [`k_theory.json`](../data/k_theory.json), ",
        "[`k_theory.csv`](../data/k_theory.csv)",
    )
    println(io)
    Rn = R.family == :akn ? ring_name(R) : "R"
    println(
        io,
        "The p-adic K-groups K_r($Rn; $(zp(p))) for 1 ≤ r ≤ $RMAX. As in [AKN, Appendix A], ",
        "each entry lists the exponents a₁ ≤ a₂ ≤ … of the decomposition ",
        "K_r($Rn; $(zp(p))) ≅ Z/$p^a₁ ⊕ Z/$p^a₂ ⊕ …, and `0` is the zero group (a blank cell ",
        "in [AKN]). K_0($Rn; $(zp(p))) = $(zp(p)).",
    )
    println(io)
    if R.family == :akn
        akn_status_paragraph(io, D, akn[(p, R.n)])
    else
        quadratic_ring_paragraph(io, R, classes, twins_of)
    end
    println(io)
    println(io, "| r | K_r($Rn; $(zp(p))) | order | status |")
    println(io, "|--:|:--|:--|:--|")
    for g in D.groups
        e = isempty(g.exponents) ? "0" : join(g.exponents, ",")
        s = sum(g.exponents; init=0)
        order = s == 0 ? "1" : "$p$(sup(s))"
        if g.status in ("x", "beyond")
            println(io, "| $(g.r) | **$e** | $order | **new** ($(g.status)) |")
        elseif g.status == "not_in_akn"
            println(io, "| $(g.r) | **$e** | $order | **new** |")
        elseif g.status == "hesselholt_madsen"
            println(io, "| $(g.r) | $e | $order | Hesselholt–Madsen |")
        else
            println(io, "| $(g.r) | $e | $order | printed |")
        end
    end
    println(io)
    println(
        io,
        "Computed with [Syntomic.jl](https://github.com/wgabrielong/Syntomic.jl) ",
        "(commit `$(first(run.syntomic_commit, 7))`) in $(fmt_time(run.wall_seconds)) on ",
        "$(run.threads) threads of an $(run.cpu), peak memory $(gib(run.peak_memory_gib)). ",
        "The cohomology of every weight and its working precision are in ",
        "[`data/cohomology/$(R.id).json`](../data/cohomology/$(R.id).json).",
    )
    return String(take!(io))
end

