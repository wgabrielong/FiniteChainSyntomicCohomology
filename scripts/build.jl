jstr(x) = JSON3.write(x)
jlist(v) = "[" * join(v, ",") * "]"

function k_theory_json(data, akn)
    io = IOBuffer()
    println(io, "{")
    println(io, "  \"format\": ", jstr(FORMAT), ",")
    println(io, "  \"akn\": ", jstr(SOURCE), ",")
    println(io, "  \"conventions\": ", jstr(CONVENTIONS), ",")
    println(io, "  \"rings\": [")
    for (k, D) in enumerate(data)
        R = D.ring
        K = R.field
        family = R.family == :akn ? "akn_appendix_A" : string(R.family)
        println(io, "    {")
        println(
            io,
            "      \"id\": $(jstr(R.id)), \"ring\": $(jstr(ring_ascii(R))), ",
            "\"family\": $(jstr(family)),",
        )
        println(
            io,
            "      \"field\": $(jstr(K.ascii)), \"lmfdb_label\": $(jstr(K.lmfdb)), ",
            "\"defining_polynomial\": $(jstr(K.poly)),",
        )
        println(
            io,
            "      \"p\": $(K.p), \"f\": $(K.f), \"e\": $(K.e), \"n\": $(R.n), ",
            "\"htilde\": $(jlist(K.htilde)), \"E\": [$(join(jlist.(K.E), ","))],",
        )
        if R.family == :akn
            a = akn[(K.p, R.n)]
            println(
                io,
                "      \"akn\": {\"section\": $(jstr(a.section)), \"page\": $(a.page), ",
                "\"label\": $(jstr(a.label)), \"max_degree\": $(a.max_degree)},",
            )
        else
            println(io, "      \"akn\": null,")
        end
        comp = (; (k => v for (k, v) in pairs(D.run) if k ∉ (:ring, :id))...)
        println(io, "      \"computation\": ", JSON3.write(comp), ",")
        println(io, "      \"groups\": [")
        rows = map(D.groups) do g
            return "        {\"r\": $(g.r), \"exponents\": $(jlist(g.exponents)), " *
                   "\"status\": \"$(g.status)\", \"new\": $(isnew(g))}"
        end
        println(io, join(rows, ",\n"))
        println(io, "      ]")
        println(io, k == length(data) ? "    }" : "    },")
    end
    println(io, "  ]")
    println(io, "}")
    return String(take!(io))
end

