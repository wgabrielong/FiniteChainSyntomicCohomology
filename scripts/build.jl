function outputs()
    data, akn = load_all()
    classes = isomorphism_classes(RINGS)
    out = Dict{String,String}(
        joinpath("data", "k_theory.json") => k_theory_json(data, akn),
        joinpath("data", "k_theory.csv") => k_theory_csv(data),
        "README.md" => readme(data, akn, classes),
    )
    twins_of = twins([D for D in data if D.ring.family == :quadratic], classes)
    for D in data
        out[joinpath("tables", "$(D.ring.id).md")] = ring_page(D, akn, classes, twins_of)
    end
    return out
end

function main(args)
    check = "--check" in args
    out = outputs()
    stale = String[]
    for (path, text) in sort(collect(out))
        file = joinpath(ROOT, path)
        current = isfile(file) ? read(file, String) : nothing
        current == text && continue
        push!(stale, path)
        check || write(file, text)
    end
    if check
        isempty(stale) || error("out of date (run scripts/build.jl): " * join(stale, ", "))
        println("all $(length(out)) files are up to date")
    else
        println("wrote ", isempty(stale) ? "nothing" : join(stale, ", "))
    end
    return nothing
end

main(ARGS)
