# Builds the tables of this repository from the computed cohomology (data/cohomology), the
# records of the runs (data/runs), the rings of scripts/rings.jl and the transcription of
# [AKN, Appendix A] (data/akn_appendix_A.json):
#
#   data/k_theory.json, data/k_theory.csv, tables/<ring id>.md, and the generated parts of
#   README.md (the tables of rings) and docs/coincidences.md (between the markers).
#
#   julia --project=scripts scripts/build.jl            # write the files
#   julia --project=scripts scripts/build.jl --check    # fail if a file differs from what
#                                                       # would be written
#
# Stops with an error unless
# - the computed cohomology is that of the ring of scripts/rings.jl;
# - every weight satisfies Angeltveit's quotient [AKN, Prop. 2.18, p. 9]:
#   |H^1(Z_p(i))| / |H^2(Z_p(i))| = q^{i(n-1)} for i ≥ 1;
# - every group printed in [AKN, Appendix A] equals the computed one;
# - for n ≤ e, where R = F_q[z]/z^n, the groups are those of Hesselholt and Madsen (see
#   `hesselholt_madsen`);
# - rings known to be isomorphic (see `isomorphism_classes`) have the same groups;
# - every field contains a root of the polynomial its name refers to (see `check_name`).
