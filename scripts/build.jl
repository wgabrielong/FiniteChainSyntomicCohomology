function fmt_time(t)
    t >= 3600 && return @sprintf("%.1f h", t / 3600)
    t >= 60 && return @sprintf("%.1f min", t / 60)
    return @sprintf("%.1f s", t)
end

# --- Hesselholt–Madsen ------------------------------------------------------------------------

# K_{2i-1}(F_q[z]/z^n; Z_p) ≅ W_{ni}(F_q)/V_n W_i(F_q) (big Witt vectors) and K_{2i-2} = 0 for
# i ≥ 2, by Hesselholt and Madsen (cited in [AKN, §1.1, p. 2]). Splitting the big Witt vectors
# into p-typical ones: with n = p^a n′, p ∤ n′, and ℓ(d) = #{j ≥ 0 : d p^j ≤ ni}, the quotient is
# ⊕ (Z/p^{h(d)})^f over 1 ≤ d ≤ ni with p ∤ d, where h(d) = ℓ(d) if n′ ∤ d and
# h(d) = min(a, ℓ(d)) if n′ | d.
function hesselholt_madsen(p, f, n, i)
    a, n1 = 0, n
    while n1 % p == 0
        n1 ÷= p
        a += 1
    end
    out = Int[]
    for d in 1:(n * i)
        d % p == 0 && continue
        l, x = 0, d
        while x <= n * i
            l += 1
            x *= p
        end
        h = d % n1 == 0 ? min(a, l) : l
        h > 0 && append!(out, fill(h, f))
    end
    return sort!(out)
end

# --- inputs -----------------------------------------------------------------------------------

readjson(parts...) = JSON3.read(read(joinpath(ROOT, parts...), String))

function load_akn()
    return Dict(
        (Int(a.p), Int(a.n)) => (;
            section=String(a.section),
            page=Int(a.page),
            label=String(a.lmfdb_label),
            max_degree=Int(a.max_degree),
            printed=Dict(Int(c.r) => Vector{Int}(c.exponents) for c in a.printed),
            x=Set{Int}(a.x),
        ) for a in readjson("data", "akn_appendix_A.json").rings
    )
end

# H^1 and H^2 of Z_p(i)(R) by weight, checked against the ring and Angeltveit's quotient.
function load_cohomology(R::Ring)
    file = joinpath("data", "cohomology", "$(R.id).json")
    K = R.field
    h = Dict{Int,Tuple{Vector{Int},Vector{Int}}}()
    for row in readjson(file).rows
        ok =
            (row.p, row.f, row.e, row.n) == (K.p, K.f, K.e, R.n) &&
            parse.(BigInt, row.htilde) == K.htilde &&
            [parse.(BigInt, c) for c in row.E] == K.E
        ok || error("$file: a row for another ring than $(R.id) of scripts/rings.jl")
        h[row.i] = (sort(Vector{Int}(row.h1)), sort(Vector{Int}(row.h2)))
    end
    issubset(1:IMAX, keys(h)) || error("$file: the weights 1:$IMAX are not all present")
    for i in 1:IMAX
        h1, h2 = h[i]
        sum(h1; init=0) - sum(h2; init=0) == K.f * i * (R.n - 1) ||
            error("$file: weight $i violates Angeltveit's quotient: H^1 = $h1, H^2 = $h2")
    end
    return h
end

function load_run(R::Ring)
    run = readjson("data", "runs", "$(R.id).json")
    run.id == R.id || error("data/runs/$(R.id).json: another ring")
    return run
end

# For n ≤ e, R = W(F_q)[z]/(E, z^n) = F_q[z]/z^n, since E ≡ z^e mod p.
is_truncated_polynomial(R::Ring) = R.n <= R.field.e

# K_r(R; Z_p) = H^1(Z_p(i)) for r = 2i - 1 and H^2(Z_p(i)) for r = 2i - 2 [AKN, Cor. 2.16, p. 9],
# with its status: for the rings of [AKN, Appendix A] "printed", "x" (marked x: not computed
# within 48 hours) or "beyond" (after the last row of the table); for the other rings
# "hesselholt_madsen" if R = F_q[z]/z^n, and "not_in_akn" otherwise.
function groups(R::Ring, h, akn)
    K = R.field
    return map(1:RMAX) do r
        i = isodd(r) ? (r + 1) ÷ 2 : r ÷ 2 + 1
        e = isodd(r) ? h[i][1] : h[i][2]
        status = if R.family == :akn
            a = akn[(K.p, R.n)]
            if haskey(a.printed, r)
                a.printed[r] == e || error(
                    "$(kr(r))($(ring_ascii(R)); Z_$(K.p)): computed $e, [AKN, Appendix A] prints $(a.printed[r])",
                )
                "printed"
            elseif r in a.x
                "x"
            else
                r > a.max_degree ||
                    error("$(kr(r))($(ring_ascii(R))): not in the transcription")
                "beyond"
            end
        elseif is_truncated_polynomial(R)
            hm = isodd(r) ? hesselholt_madsen(K.p, K.f, R.n, i) : Int[]
            e == hm || error(
                "$(kr(r)) of $(R.id) = F_$(K.p^K.f)[z]/z^$(R.n): computed $e, Hesselholt–Madsen gives $hm",
            )
            "hesselholt_madsen"
        else
            "not_in_akn"
        end
        return (; r, exponents=e, status)
    end
end

isnew(g) = g.status in ("x", "beyond", "not_in_akn")
count_status(D, s) = count(g -> g.status == s, D.groups)

# Whether R = Z_p[z]/(E, z^n) and R′ = Z_p[z]/(E′, z^n) are isomorphic, for Eisenstein E, E′ of
# degree 2 over Z_p (f = 1, e = 2). Write E = z^2 + c1 z + c0, so z^2 = -c1 z - c0 with
# c0 = p·(unit). Then the ideal (z^n) of Z_p[z]/(E) is p^⌈n/2⌉ Z_p ⊕ p^⌊n/2⌋ Z_p z, so R is the
# ring of the a + b z with a mod p^⌈n/2⌉ and b mod p^⌊n/2⌋. An isomorphism R′ → R sends z to a
# uniformizer w = a + b z of R (p | a, p ∤ b) with E′(w) = 0. Conversely such a w gives a
# surjection R′ → R (w generates R), which is bijective since both rings have p^n elements. So
# the rings are isomorphic exactly when R has such a w; the search below is exhaustive.
function quadratic_isomorphic(p, n, E, E′)
    A, B = p^cld(n, 2), p^fld(n, 2)
    c0, c1 = E[1][1], E[2][1]
    d0, d1 = E′[1][1], E′[2][1]
    for a in 0:p:(A - 1), b in 1:(B - 1)
        b % p == 0 && continue
        # w^2 = a^2 - b^2 c0 + (2ab - b^2 c1) z, and E′(w) = w^2 + d1 w + d0
        x = mod(a^2 - b^2 * c0 + d1 * a + d0, A)
        y = mod(2 * a * b - b^2 * c1 + d1 * b, B)
        x == 0 && y == 0 && return true
    end
    return false
end

# The rings that are isomorphic, as lists of ring ids (only lists of more than one ring), in
# the order of scripts/rings.jl. Two rings are isomorphic
# - if they have the same p, f, e, n and h̃, and E ≡ E′ modulo p^⌈n/e⌉: if E′ = E + p^k g with
#   k = ⌈n/e⌉, then p^k = (unit)·z^{ek} lies in (E, z^n) and in (E′, z^n), so the two ideals
#   are equal;
# - for f = 1 and e = 2, exactly when `quadratic_isomorphic` says so.
# For the rings of this repository this gives all isomorphisms: the only rings with the same
# p, f, e and n are the O_K/ϖ^n of the ramified quadratic extensions of Q_2.
function isomorphism_classes(rings)
    parent = Dict(R.id => R.id for R in rings)
    root(x) = parent[x] == x ? x : root(parent[x])
    join!(x, y) = (parent[root(x)] = root(y))
    for (k, R) in enumerate(rings), R′ in rings[(k + 1):end]
        K, K′ = R.field, R′.field
        (K.p, K.f, K.e, R.n, K.htilde) == (K′.p, K′.f, K′.e, R′.n, K′.htilde) || continue
        m = big(K.p)^cld(R.n, K.e)
        same = [mod.(c, m) for c in K.E] == [mod.(c, m) for c in K′.E]
        if same || (K.f == 1 && K.e == 2 && quadratic_isomorphic(K.p, R.n, K.E, K′.E))
            join!(R.id, R′.id)
        end
    end
    classes = Dict{String,Vector{String}}()
    for R in rings
        push!(get!(classes, root(R.id), String[]), R.id)
    end
    position(id) = findfirst(R -> R.id == id, RINGS)
    out = [sort(c; by=position) for c in values(classes) if length(c) > 1]
    return sort(out; by=c -> position(c[1]))
end

function load_all()
    akn = load_akn()
    Set(keys(akn)) == Set((R.field.p, R.n) for R in AKN_RINGS) ||
        error("data/akn_appendix_A.json: unexpected rings")
    data = map(RINGS) do R
        return (; ring=R, run=load_run(R), groups=groups(R, load_cohomology(R), akn))
    end
    byid = Dict(D.ring.id => D for D in data)
    for class in isomorphism_classes(RINGS)
        ref = byid[class[1]]
        for id in class[2:end]
            [g.exponents for g in byid[id].groups] == [g.exponents for g in ref.groups] || error("$id and $(class[1]) are isomorphic but their groups differ")
        end
    end
    return data, akn
end

