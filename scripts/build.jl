function akn_block(data, akn)
    io = IOBuffer()
    println(
        io,
        "| ring | [AKN] | printed in [AKN] | x in [AKN] | new here | time | peak memory |",
    )
    println(io, "|:--|:--|--:|--:|--:|--:|--:|")
    rows = [D for D in data if D.ring.family == :akn]
    for D in rows
        R = D.ring
        a = akn[(R.field.p, R.n)]
        nx = count_status(D, "x")
        println(
            io,
            "| [$(ring_name(R))](tables/$(R.id).md) | §$(a.section), p. $(a.page): ",
            "K_1–K_$(a.max_degree) | $(count_status(D, "printed")) | $(nx == 0 ? "—" : nx) | ",
            "**$(count(isnew, D.groups))** | $(fmt_time(D.run.wall_seconds)) | ",
            "$(gib(D.run.peak_memory_gib)) |",
        )
    end
    all_ = [g for D in rows for g in D.groups]
    print(
        io,
        "| **all $(length(rows))** | | $(count(g -> g.status == "printed", all_)) | ",
        "$(count(g -> g.status == "x", all_)) | **$(thousands(count(isnew, all_)))** | ",
        "$(fmt_time(sum(D.run.wall_seconds for D in rows))) | |",
    )
    return String(take!(io))
end

function fields_block(data, family, fields)
    io = IOBuffer()
    rows = [D for D in data if D.ring.family == family]
    byfield = Dict((D.ring.field.p, D.ring.field.key, D.ring.n) => D for D in rows)
    ns = sort(unique(D.ring.n for D in rows))
    println(
        io, "| K | LMFDB | e | f | polynomial | ", join(("n = $n" for n in ns), " | "), " |"
    )
    println(io, "|:--|:--|--:|--:|:--|", join(("--:" for _ in ns), "|"), "|")
    for K in fields
        cells = map(ns) do n
            D = byfield[(K.p, K.key, n)]
            return "[O_K/ϖ$(sup(n))](tables/$(D.ring.id).md) ($(fmt_time(D.run.wall_seconds)))"
        end
        println(
            io,
            "| $(field_name(K)) | $(lmfdb_link(K)) | $(K.e) | $(K.f) | $(poly_pretty(K.poly)) | ",
            join(cells, " | "),
            " |",
        )
    end
    all_ = [g for D in rows for g in D.groups]
    nhm = count(g -> g.status == "hesselholt_madsen", all_)
    big_ = rows[argmax([D.run.wall_seconds for D in rows])]
    truncated = if family == :quadratic
        "the rings O_K/ϖ² ≅ F_p[z]/z² (K ramified)"
    else
        "the rings O_K/ϖ² ≅ F_p[z]/z² and O_K/ϖ³ ≅ F_p[z]/z³ (K ramified)"
    end
    println(io)
    println(
        io,
        "$(length(rows)) rings and $(thousands(length(all_))) groups: ",
        "**$(thousands(count(isnew, all_))) new** relative to [AKN], and the $(thousands(nhm)) groups of ",
        "$truncated, which agree with Hesselholt and Madsen. The ",
        "times are those of all $IMAX weights on 8 threads; all rings took ",
        "$(fmt_time(sum(D.run.wall_seconds for D in rows))), and the longest, ",
        "$(ring_title(big_.ring)), took $(fmt_time(big_.run.wall_seconds)) and ",
        "$(gib(big_.run.peak_memory_gib)) of memory.",
    )
    return chomp(String(take!(io)))
end

# Rings with the same p, f and n, not isomorphic, with equal tables: id => the other ids.
function twins(rows, classes)
    table(D) = [g.exponents for g in D.groups]
    same_class(a, b) = any(c -> a in c && b in c, classes)
    key(D) = (D.ring.field.p, D.ring.field.f, D.ring.n)
    return Dict(
        D.ring.id => [
            E.ring.id for E in rows if key(E) == key(D) &&
                E.ring.id != D.ring.id &&
                !same_class(D.ring.id, E.ring.id) &&
                table(E) == table(D)
        ] for D in rows
    )
end

# The rings O_K/ϖ^n of the ramified fields of degree e of each Q_p up to isomorphism
# (`isomorphism_classes` is exact for them), with what their K-groups say.
function coincidences(rows, classes, e)
    io = IOBuffer()
    byid = Dict(D.ring.id => D for D in rows)
    table(id) = [g.exponents for g in byid[id].groups]
    names(ids) = join([ring_by_id(id).field.name for id in ids], ", ")
    elements = if e == 2
        "a + bϖ with a mod p^⌈n/2⌉ and b mod p^⌊n/2⌋"
    else
        "a + bϖ + cϖ² with a mod p^⌈n/3⌉, b mod p^⌈(n−1)/3⌉ and c mod p^⌈(n−2)/3⌉"
    end
    println(
        io,
        "For a ramified $(e == 2 ? "quadratic" : "cubic") extension K of Q_p, the ring O_K/ϖⁿ ",
        "consists of the pⁿ elements $elements. Two such rings are isomorphic ",
        "exactly when one of them contains a uniformizer that is a root of the other's defining ",
        "polynomial. `ramified_isomorphic` in [`scripts/build.jl`](../scripts/build.jl) searches ",
        "for such a root among all uniformizers, for every pair. Isomorphic rings have the same ",
        "K-groups, and the tables agree:",
    )
    println(io)
    println(io, "| p | n | the rings O_K/ϖⁿ up to isomorphism, by K | their K-groups |")
    println(io, "|--:|--:|:--|:--|")
    single = Int[]
    for p in sort(unique(D.ring.field.p for D in rows)),
        n in sort(unique(D.ring.n for D in rows))

        ram = [
            D.ring.id for
            D in rows if D.ring.field.p == p && D.ring.n == n && D.ring.field.e == e
        ]
        isempty(ram) && continue
        if length(ram) == 1
            p in single || push!(single, p)
            continue
        end
        all_fields = length(ram) == 2 ? "both fields" : "all $(length(ram)) fields"
        parts = Vector{Vector{String}}()
        for id in ram
            k = findfirst(c -> id in c, classes)
            c = k === nothing ? [id] : filter(in(ram), classes[k])
            c in parts || push!(parts, c)
        end
        desc = if length(parts) == 1
            if n <= e
                "one ring, F$(sub(p))[z]/z$(sup(n)), for $all_fields"
            elseif n == 3 && p == 2 && e == 2
                "one ring, Z/4[z]/(z² − 2, 2z), for $all_fields"
            else
                "one ring for $all_fields"
            end
        else
            "$(length(parts)) rings: " * join(("{$(names(c))}" for c in parts), " · ")
        end
        firsts = Int[]
        equal = String[]
        for a in eachindex(parts), b in (a + 1):length(parts)
            ta, tb = table(parts[a][1]), table(parts[b][1])
            r = findfirst(r -> ta[r] != tb[r], 1:RMAX)
            if r === nothing
                push!(equal, "{$(names(parts[a]))} and {$(names(parts[b]))}")
            else
                push!(firsts, r)
            end
        end
        cell = String[]
        if !isempty(equal)
            push!(
                cell,
                "**the same K_1–K_$RMAX** for $(join(equal, "; ")), although the rings are " *
                "not isomorphic",
            )
        end
        if !isempty(firsts)
            lo, hi = extrema(firsts)
            span = lo == hi ? "K_$lo" : "K_$lo to K_$hi"
            push!(cell, (isempty(equal) ? "" : "any other two ") * "first differ in $span")
        end
        println(io, "| $p | $n | $desc | $(isempty(cell) ? "—" : join(cell, "; ")) |")
    end
    if !isempty(single)
        println(io)
        qs = join(("Q$(sub(p))" for p in single), " and ")
        one = length(single) == 1
        print(
            io,
            "$qs $(one ? "has" : "each have") one ramified $(e == 2 ? "quadratic" : "cubic") ",
            "field, so $(one ? "it is" : "they are") not in the table.",
        )
    end
    return String(take!(io))
end

# A name of the ring of a class of isomorphic rings, if it has a simple one.
function ring_description(ids)
    R = ring_by_id(ids[1])
    K = R.field
    R.family == :akn && return ring_name(R)
    is_truncated_polynomial(R) && return "F$(sub(K.p^K.f))[z]/z$(sup(R.n))"
    (K.p, K.f, K.e, R.n) == (2, 1, 2, 3) && return "Z/4[z]/(z² − 2, 2z)"
    return nothing
end

# The coincidences between the families: the sets of rings with the same p, f and n and
# equal tables that contain rings of more than one family, split into classes of isomorphic
# rings.
function across(data, classes)
    io = IOBuffer()
    table(D) = [g.exponents for g in D.groups]
    class_of(id) = (k=findfirst(c -> id in c, classes); k === nothing ? [id] : classes[k])
    position(id) = findfirst(R -> R.id == id, RINGS)
    sets = Dict{Any,Vector{String}}()
    for D in data
        K = D.ring.field
        push!(get!(sets, (K.p, K.f, D.ring.n, table(D)), String[]), D.ring.id)
    end
    rows = [
        sort(ids; by=position) for
        ids in values(sets) if length(unique(ring_by_id(id).family for id in ids)) > 1
    ]
    sort!(rows; by=ids -> (ring_by_id(ids[1]).field.p, ring_by_id(ids[1]).n))
    println(
        io,
        "The rings with the same K_1–K_$RMAX that belong to different families, split into ",
        "classes of isomorphic rings:",
    )
    println(io)
    println(io, "| p | n | the rings, up to isomorphism | |")
    println(io, "|--:|--:|:--|:--|")
    for ids in rows
        R = ring_by_id(ids[1])
        parts = unique(filter(in(ids), class_of(id)) for id in ids)
        cells = map(parts) do c
            fields = [ring_by_id(id) for id in c if ring_by_id(id).family != :akn]
            names = join(("[$(S.field.name)](../tables/$(S.id).md)" for S in fields), ", ")
            d = ring_description(c)
            isempty(fields) && return "[$(d)](../tables/$(c[1]).md)"
            what = "O_K/ϖ$(sup(R.n)) for K = $names"
            return d === nothing ? what : "$d: $what"
        end
        relation = if length(parts) == 1
            "the same ring"
        else
            "**not isomorphic, with the same K_1–K_$RMAX**"
        end
        println(io, "| $(R.field.p) | $(R.n) | $(join(cells, " · ")) | $relation |")
    end
    return chomp(String(take!(io)))
end

function replace_block(text, name, content)
    _, b, e = MARKS[name]
    i = findfirst(b, text)
    j = findfirst(e, text)
    (i === nothing || j === nothing) &&
        error("$(MARKS[name][1]): the $name markers are missing")
    return text[1:last(i)] * "\n" * content * "\n" * text[first(j):end]
end

# README.md and docs/coincidences.md with their generated parts.
function documents(data, akn, classes)
    blocks = Dict(
        "akn" => akn_block(data, akn), "across-coincidences" => across(data, classes)
    )
    for (family, fields, e) in
        ((:quadratic, QUADRATIC_FIELDS, 2), (:cubic, CUBIC_FIELDS, 3))
        rows = [D for D in data if D.ring.family == family]
        blocks[string(family)] = fields_block(data, family, fields)
        blocks["$family-coincidences"] = coincidences(rows, classes, e)
    end
    out = Dict{String,String}()
    for file in unique(first.(values(MARKS)))
        text = read(joinpath(ROOT, file), String)
        for (name, (f, _, _)) in MARKS
            f == file && (text = replace_block(text, name, blocks[name]))
        end
        out[file] = text
    end
    return out
end

# --- main -------------------------------------------------------------------------------------

function outputs()
    data, akn = load_all()
    classes = isomorphism_classes(RINGS)
    out = Dict{String,String}(
        joinpath("data", "k_theory.json") => k_theory_json(data, akn),
        joinpath("data", "k_theory.csv") => k_theory_csv(data),
    )
    merge!(out, documents(data, akn, classes))
    twins_of = twins(data, classes)
    for D in data
        out[joinpath("tables", "$(D.ring.id).md")] = ring_page(D, akn, classes, twins_of)
    end
    return out
end

function main(args)
    check = "--check" in args
    out = outputs()
    stale = String[]
    for (path, text) in sort(collect(out))
        file = joinpath(ROOT, path)
        current = isfile(file) ? read(file, String) : nothing
        current == text && continue
        push!(stale, path)
        check || write(file, text)
    end
    if check
        isempty(stale) || error("out of date (run scripts/build.jl): " * join(stale, ", "))
        println("all $(length(out)) files are up to date")
    else
        println("wrote ", isempty(stale) ? "nothing" : join(stale, ", "))
    end
    return nothing
end

