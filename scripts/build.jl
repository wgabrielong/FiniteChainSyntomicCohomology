function akn_block(data, akn)
    io = IOBuffer()
    println(
        io,
        "| ring | [AKN] | printed in [AKN] | x in [AKN] | new here | time | peak memory |",
    )
    println(io, "|:--|:--|--:|--:|--:|--:|--:|")
    rows = [D for D in data if D.ring.family == :akn]
    for D in rows
        R = D.ring
        a = akn[(R.field.p, R.n)]
        nx = count_status(D, "x")
        println(
            io,
            "| [$(ring_name(R))](tables/$(R.id).md) | §$(a.section), p. $(a.page): ",
            "K_1–K_$(a.max_degree) | $(count_status(D, "printed")) | $(nx == 0 ? "—" : nx) | ",
            "**$(count(isnew, D.groups))** | $(fmt_time(D.run.wall_seconds)) | ",
            "$(gib(D.run.peak_memory_gib)) |",
        )
    end
    all_ = [g for D in rows for g in D.groups]
    print(
        io,
        "| **all $(length(rows))** | | $(count(g -> g.status == "printed", all_)) | ",
        "$(count(g -> g.status == "x", all_)) | **$(thousands(count(isnew, all_)))** | ",
        "$(fmt_time(sum(D.run.wall_seconds for D in rows))) | |",
    )
    return String(take!(io))
end

function quadratic_block(data, classes)
    io = IOBuffer()
    rows = [D for D in data if D.ring.family == :quadratic]
    byfield = Dict((D.ring.field.key, D.ring.n) => D for D in rows)
    ns = sort(unique(D.ring.n for D in rows))
    println(
        io, "| K | LMFDB | e | f | polynomial | ", join(("n = $n" for n in ns), " | "), " |"
    )
    println(io, "|:--|:--|--:|--:|:--|", join(("--:" for _ in ns), "|"), "|")
    for K in QUADRATIC_FIELDS
        cells = map(ns) do n
            D = byfield[(K.key, n)]
            return "[O_K/ϖ$(sup(n))](tables/$(D.ring.id).md) ($(fmt_time(D.run.wall_seconds)))"
        end
        println(
            io,
            "| $(field_name(K)) | $(lmfdb_link(K)) | $(K.e) | $(K.f) | $(poly_pretty(K.poly)) | ",
            join(cells, " | "),
            " |",
        )
    end
    all_ = [g for D in rows for g in D.groups]
    nhm = count(g -> g.status == "hesselholt_madsen", all_)
    big_ = rows[argmax([D.run.wall_seconds for D in rows])]
    println(io)
    println(
        io,
        "$(length(rows)) rings and $(thousands(length(all_))) groups: ",
        "**$(thousands(count(isnew, all_))) new** relative to [AKN], and the $nhm groups of the ",
        "rings O_K/ϖ² ≅ F₂[z]/z² (K ramified), which agree with Hesselholt and Madsen. The ",
        "times are those of all $IMAX weights on 8 threads; all rings took ",
        "$(fmt_time(sum(D.run.wall_seconds for D in rows))), and the longest, ",
        "$(ring_title(big_.ring)), took $(fmt_time(big_.run.wall_seconds)) and ",
        "$(gib(big_.run.peak_memory_gib)) of memory.",
    )
    return chomp(String(take!(io)))
end

# Rings with the same n, not isomorphic, whose tables are equal: id => the other ids.
function twins(rows, classes)
    table(D) = [g.exponents for g in D.groups]
    same_class(a, b) = any(c -> a in c && b in c, classes)
    return Dict(
        D.ring.id => [
            E.ring.id for E in rows if E.ring.n == D.ring.n &&
                E.ring.id != D.ring.id &&
                E.ring.field.e == D.ring.field.e &&
                !same_class(D.ring.id, E.ring.id) &&
                table(E) == table(D)
        ] for D in rows
    )
end

# The rings O_K/ϖ^n of the ramified quadratic fields up to isomorphism (`isomorphism_classes`
# is exact for them), with what their K-groups say.
function coincidences(rows, classes)
    io = IOBuffer()
    byid = Dict(D.ring.id => D for D in rows)
    table(id) = [g.exponents for g in byid[id].groups]
    names(ids) = join([ring_by_id(id).field.name for id in ids], ", ")
    println(
        io,
        "For the six ramified fields K, the ring O_K/ϖⁿ consists of the 2ⁿ elements a + bϖ with ",
        "a mod 2^⌈n/2⌉ and b mod 2^⌊n/2⌋. Two of these rings are isomorphic exactly when one ",
        "of them contains a uniformizer that is a root of the other's defining polynomial. ",
        "`quadratic_isomorphic` in [`scripts/build.jl`](scripts/build.jl) searches for such a ",
        "root among all uniformizers, for every pair. Isomorphic rings have the same K-groups, ",
        "and the tables agree:",
    )
    println(io)
    println(io, "| n | the rings O_K/ϖⁿ up to isomorphism, by K | their K-groups |")
    println(io, "|--:|:--|:--|")
    for n in sort(unique(D.ring.n for D in rows))
        ram = [D.ring.id for D in rows if D.ring.n == n && D.ring.field.e == 2]
        parts = Vector{Vector{String}}()
        for id in ram
            k = findfirst(c -> id in c, classes)
            c = k === nothing ? [id] : classes[k]
            c in parts || push!(parts, c)
        end
        desc = if length(parts) == 1
            if n == 2
                "one ring, F₂[z]/z², for all six fields"
            elseif n == 3
                "one ring, Z/4[z]/(z² − 2, 2z), for all six fields"
            else
                "one ring for all six fields"
            end
        else
            "$(length(parts)) rings: " * join(("{$(names(c))}" for c in parts), " · ")
        end
        firsts = Int[]
        equal = String[]
        for a in eachindex(parts), b in (a + 1):length(parts)
            ta, tb = table(parts[a][1]), table(parts[b][1])
            r = findfirst(r -> ta[r] != tb[r], 1:RMAX)
            if r === nothing
                push!(equal, "{$(names(parts[a]))} and {$(names(parts[b]))}")
            else
                push!(firsts, r)
            end
        end
        cell = String[]
        if !isempty(equal)
            push!(
                cell,
                "**the same K_1–K_$RMAX** for $(join(equal, "; ")), although the rings are " *
                "not isomorphic",
            )
        end
        if !isempty(firsts)
            lo, hi = extrema(firsts)
            span = lo == hi ? "K_$lo" : "K_$lo to K_$hi"
            push!(cell, (isempty(equal) ? "" : "any other two ") * "first differ in $span")
        end
        println(io, "| $n | $desc | $(isempty(cell) ? "—" : join(cell, "; ")) |")
    end
    println(io)
    print(
        io,
        "The unramified field Q₂(√−3) gives W_n(F₄), whose residue field is F₄, so it is none ",
        "of these rings.",
    )
    return String(take!(io))
end

function replace_block(text, name, content)
    b, e = MARKS[name]
    i = findfirst(b, text)
    j = findfirst(e, text)
    (i === nothing || j === nothing) && error("README.md: the $name markers are missing")
    return text[1:last(i)] * "\n" * content * "\n" * text[first(j):end]
end

function readme(data, akn, classes)
    text = read(joinpath(ROOT, "README.md"), String)
    text = replace_block(text, "akn", akn_block(data, akn))
    text = replace_block(text, "quadratic", quadratic_block(data, classes))
    rows = [D for D in data if D.ring.family == :quadratic]
    return replace_block(text, "coincidences", coincidences(rows, classes))
end

