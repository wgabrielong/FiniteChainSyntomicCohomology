readjson(parts...) = JSON3.read(read(joinpath(ROOT, parts...), String))

function load_akn()
    return Dict(
        (Int(a.p), Int(a.n)) => (;
            section=String(a.section),
            page=Int(a.page),
            label=String(a.lmfdb_label),
            max_degree=Int(a.max_degree),
            printed=Dict(Int(c.r) => Vector{Int}(c.exponents) for c in a.printed),
            x=Set{Int}(a.x),
        ) for a in readjson("data", "akn_appendix_A.json").rings
    )
end

# H^1 and H^2 of Z_p(i)(R) by weight, checked against the ring and Angeltveit's quotient.
function load_cohomology(R::Ring)
    file = joinpath("data", "cohomology", "$(R.id).json")
    K = R.field
    h = Dict{Int,Tuple{Vector{Int},Vector{Int}}}()
    for row in readjson(file).rows
        ok =
            (row.p, row.f, row.e, row.n) == (K.p, K.f, K.e, R.n) &&
            parse.(BigInt, row.htilde) == K.htilde &&
            [parse.(BigInt, c) for c in row.E] == K.E
        ok || error("$file: a row for another ring than $(R.id) of scripts/rings.jl")
        h[row.i] = (sort(Vector{Int}(row.h1)), sort(Vector{Int}(row.h2)))
    end
    issubset(1:IMAX, keys(h)) || error("$file: the weights 1:$IMAX are not all present")
    for i in 1:IMAX
        h1, h2 = h[i]
        sum(h1; init=0) - sum(h2; init=0) == K.f * i * (R.n - 1) ||
            error("$file: weight $i violates Angeltveit's quotient: H^1 = $h1, H^2 = $h2")
    end
    return h
end

function load_run(R::Ring)
    run = readjson("data", "runs", "$(R.id).json")
    run.id == R.id || error("data/runs/$(R.id).json: another ring")
    return run
end

# For n ≤ e, R = W(F_q)[z]/(E, z^n) = F_q[z]/z^n, since E ≡ z^e mod p.
is_truncated_polynomial(R::Ring) = R.n <= R.field.e

# K_r(R; Z_p) = H^1(Z_p(i)) for r = 2i - 1 and H^2(Z_p(i)) for r = 2i - 2 [AKN, Cor. 2.16, p. 9],
# with its status: for the rings of [AKN, Appendix A] "printed", "x" (marked x: not computed
# within 48 hours) or "beyond" (after the last row of the table); for the other rings
# "hesselholt_madsen" if R = F_q[z]/z^n, and "not_in_akn" otherwise.
function groups(R::Ring, h, akn)
    K = R.field
    return map(1:RMAX) do r
        i = isodd(r) ? (r + 1) ÷ 2 : r ÷ 2 + 1
        e = isodd(r) ? h[i][1] : h[i][2]
        status = if R.family == :akn
            a = akn[(K.p, R.n)]
            if haskey(a.printed, r)
                a.printed[r] == e || error(
                    "$(kr(r))($(ring_ascii(R)); Z_$(K.p)): computed $e, [AKN, Appendix A] prints $(a.printed[r])",
                )
                "printed"
            elseif r in a.x
                "x"
            else
                r > a.max_degree ||
                    error("$(kr(r))($(ring_ascii(R))): not in the transcription")
                "beyond"
            end
        elseif is_truncated_polynomial(R)
            hm = isodd(r) ? hesselholt_madsen(K.p, K.f, R.n, i) : Int[]
            e == hm || error(
                "$(kr(r)) of $(R.id) = F_$(K.p^K.f)[z]/z^$(R.n): computed $e, Hesselholt–Madsen gives $hm",
            )
            "hesselholt_madsen"
        else
            "not_in_akn"
        end
        return (; r, exponents=e, status)
    end
end

isnew(g) = g.status in ("x", "beyond", "not_in_akn")
count_status(D, s) = count(g -> g.status == s, D.groups)

# Whether R = Z_p[z]/(E, z^n) and R′ = Z_p[z]/(E′, z^n) are isomorphic, for Eisenstein E, E′
# of degree e over Z_p (f = 1). Write E = z^e + c_{e-1} z^{e-1} + … + c_0. In Z_p[z]/(E) the
# element a z^k (0 ≤ k < e) has valuation e v_p(a) + k, so the ideal (z^n) is the sum of the
# p^⌈(n-k)/e⌉ Z_p z^k, and R is the ring of the Σ a_k z^k with a_k mod p^⌈(n-k)/e⌉. An
# isomorphism R′ → R sends z to a uniformizer w = Σ a_k z^k of R (p | a_0, p ∤ a_1) with
# E′(w) = 0. Conversely such a w gives a surjection R′ → R (w generates R), which is
# bijective since both rings have p^n elements. So the rings are isomorphic exactly when R
# has such a w; the search below is exhaustive.
function ramified_isomorphic(p, e, n, E, E′)
    mods = [p^cld(n - k, e) for k in 0:(e - 1)]
    c = [E[k + 1][1] for k in 0:(e - 1)]
    d = [E′[k + 1][1] for k in 0:(e - 1)]
    function mul(x, y)
        r = zeros(Int, 2 * e - 1)
        for i in 1:e, j in 1:e
            r[i + j - 1] += x[i] * y[j]
        end
        for k in (2 * e - 1):-1:(e + 1)          # r[k]: the coefficient of z^(k-1), k > e
            t = r[k]
            for i in 1:e
                r[k - e + i - 1] -= t * c[i]
            end
        end
        return mod.(r[1:e], mods)
    end
    ranges = [k == 0 ? (0:p:(mods[1] - 1)) : (0:(mods[k + 1] - 1)) for k in 0:(e - 1)]
    for w in Iterators.product(ranges...)
        w[2] % p == 0 && continue
        x = collect(w)
        acc = [1; zeros(Int, e - 1)]                # E′(w) by Horner's rule
        for k in (e - 1):-1:0
            acc = mul(acc, x)
            acc[1] += d[k + 1]
        end
        all(iszero, mod.(acc, mods)) && return true
    end
    return false
end

# The rings that are isomorphic, as lists of ring ids (only lists of more than one ring), in
# the order of scripts/rings.jl. Two rings with the same p, f, n and h̃ are isomorphic
# - if n ≤ e and n ≤ e′, since both are F_q[z]/z^n;
# - if e = e′ and E ≡ E′ modulo p^⌈n/e⌉: if E′ = E + p^k g with k = ⌈n/e⌉, then
#   p^k = (unit)·z^{ek} lies in (E, z^n) and in (E′, z^n), so the two ideals are equal;
# - for f = 1 and e = e′ ≥ 2, exactly when `ramified_isomorphic` says so.
# For the rings of this repository this gives all isomorphisms. The residue field F_q and n
# are invariants of R. If n > e, then p lies in 𝔪^e but not in 𝔪^{e+1}, so rings with
# different e are isomorphic only if both are F_q[z]/z^n. And for given p, f and e there is
# either one field (e = 1) or f = 1.
function isomorphism_classes(rings)
    parent = Dict(R.id => R.id for R in rings)
    root(x) = parent[x] == x ? x : root(parent[x])
    join!(x, y) = (parent[root(x)] = root(y))
    for (k, R) in enumerate(rings), R′ in rings[(k + 1):end]
        K, K′ = R.field, R′.field
        (K.p, K.f, R.n, K.htilde) == (K′.p, K′.f, R′.n, K′.htilde) || continue
        iso = if is_truncated_polynomial(R) || is_truncated_polynomial(R′)
            is_truncated_polynomial(R) && is_truncated_polynomial(R′)
        elseif K.e != K′.e
            false
        else
            m = big(K.p)^cld(R.n, K.e)
            same = [mod.(c, m) for c in K.E] == [mod.(c, m) for c in K′.E]
            ramified = K.f == 1 && K.e >= 2
            same || (ramified && ramified_isomorphic(K.p, K.e, R.n, K.E, K′.E))
        end
        iso && join!(R.id, R′.id)
    end
    classes = Dict{String,Vector{String}}()
    for R in rings
        push!(get!(classes, root(R.id), String[]), R.id)
    end
    position(id) = findfirst(R -> R.id == id, RINGS)
    out = [sort(c; by=position) for c in values(classes) if length(c) > 1]
    return sort(out; by=c -> position(c[1]))
end

