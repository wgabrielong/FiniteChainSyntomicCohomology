# Arithmetic in O_K/p^j, where O_K = Z_p[x]/(P) for the LMFDB polynomial P of K, of
# degree d = ef, which is Eisenstein (f = 1) or irreducible modulo p (e = 1). Elements and
# polynomials are coefficient vectors, from low to high degree.
function ok_mul(a, b, P, M)
    d = length(P) - 1
    r = zeros(Int128, 2 * d - 1)
    for i in 1:d, j in 1:d
        r[i + j - 1] = mod(r[i + j - 1] + a[i] * b[j], M)
    end
    for k in (2 * d - 1):-1:(d + 1)              # r[k]: the coefficient of x^(k-1), k > d
        t = r[k]
        for i in 1:d
            r[k - d + i - 1] = mod(r[k - d + i - 1] - t * P[i], M)
        end
    end
    return r[1:d]
end

function ok_eval(g, β, P, M)
    acc = zeros(Int128, length(β))
    for k in length(g):-1:1
        acc = ok_mul(acc, β, P, M)
        acc[1] = mod(acc[1] + g[k], M)
    end
    return acc
end

# The valuation of a ≠ 0 mod p^j, normalized by v(p) = e, or e j if a ≡ 0 mod p^j: x^k has
# valuation k if P is Eisenstein, and 0 otherwise.
function ok_val(a, p, e, j)
    v = e * j
    for (k, c) in enumerate(a)
        c == 0 && continue
        w = 0
        while c % p == 0
            c ÷= p
            w += 1
        end
        v = min(v, e * w + (e > 1 ? k - 1 : 0))
    end
    return v
end

# Whether g ∈ Z[x] has a root in O_K = Z_p[x]/(P). A root ρ gives, for every j, an element
# β = ρ mod p^j with g(β) ≡ 0 mod p^j; so if no β mod p^j has g(β) ≡ 0 mod p^j, g has no
# root. Conversely, if g(β) ≡ 0 mod p^j and e j > 2 v(g′(β)), then v(g(β)) > 2 v(g′(β))
# for every lift of β to O_K, and Newton's lemma gives a root. The search lifts the
# solutions modulo p^j one p-adic digit at a time.
function has_root(g, P, p, e; jmax=16)
    d = length(P) - 1
    g′ = [k * g[k + 1] for k in 1:(length(g) - 1)]
    cands = [zeros(Int128, d)]
    for j in 1:jmax
        M, s = Int128(p)^j, Int128(p)^(j - 1)
        next = Vector{Vector{Int128}}()
        for b in cands, t in Iterators.product(ntuple(_ -> 0:(p - 1), d)...)
            β = [mod(b[k] + s * t[k], M) for k in 1:d]
            all(iszero, ok_eval(g, β, P, M)) && push!(next, β)
        end
        isempty(next) && return false
        any(β -> e * j > 2 * ok_val(ok_eval(g′, β, P, M), p, e, j), next) && return true
        cands = next
    end
    return error("has_root: undecided at precision p^$jmax")
end

function cyclotomic(m)
    q = [-1; zeros(Int, m - 1); 1]          # x^m - 1, divided by Φ_k for k | m, k < m
    for k in 1:(m - 1)
        m % k == 0 || continue
        φ = cyclotomic(k)
        out = zeros(Int, length(q) - length(φ) + 1)
        for i in length(out):-1:1
            out[i] = q[i + length(φ) - 1]
            q[i:(i + length(φ) - 1)] .-= out[i] .* φ
        end
        all(iszero, q) || error("Φ_$k does not divide x^$m - 1")
        q = out
    end
    return q
end

# The polynomial whose root generates K by the name of K, or nothing: x^2 - d for Q_p(√d),
# x^3 - a for Q_p(∛a), Φ_m for Q_p(ζ_m) and x^3 - 3x + 1 for Q₃(ζ₉)⁺ = Q₃(ζ₉ + ζ₉⁻¹).
function name_polynomial(K::Field)
    m = match(r"^sqrt(-?\d+)$", K.key)
    m === nothing || return [-parse(Int, m[1]), 0, 1]
    m = match(r"^cbrt(\d+)$", K.key)
    m === nothing || return [-parse(Int, m[1]), 0, 0, 1]
    K.key == "zeta9plus" && return [1, -3, 0, 1]
    m = match(r"^zeta(\d+)$", K.key)
    m === nothing || return cyclotomic(parse(Int, m[1]))
    return nothing
end

defining_polynomial(K::Field) = K.e == 1 ? K.htilde : [c[1] for c in K.E]

# The name of K is right if the polynomial g of `name_polynomial` has a root in K but none
# in Q_p: since [K : Q_p] is prime, that root then generates K.
function check_name(K::Field)
    g = name_polynomial(K)
    g === nothing && return nothing
    has_root(g, defining_polynomial(K), K.p, K.e) ||
        error("$(K.ascii): the field has no root of $g")
    has_root(g, [0, 1], K.p, 1) && error("$(K.ascii): $g has a root in Q_$(K.p)")
    return nothing
end

function load_all()
    akn = load_akn()
    Set(keys(akn)) == Set((R.field.p, R.n) for R in AKN_RINGS) ||
        error("data/akn_appendix_A.json: unexpected rings")
    foreach(check_name, unique(R.field for R in RINGS))
    data = map(RINGS) do R
        return (; ring=R, run=load_run(R), groups=groups(R, load_cohomology(R), akn))
    end
    byid = Dict(D.ring.id => D for D in data)
    for class in isomorphism_classes(RINGS)
        ref = byid[class[1]]
        for id in class[2:end]
            [g.exponents for g in byid[id].groups] == [g.exponents for g in ref.groups] || error("$id and $(class[1]) are isomorphic but their groups differ")
        end
    end
    return data, akn
end

